"""
Build the Springer Nature (Empirical Software Engineering) version of the
manuscript from the Elsevier sources in manuscript/latex.

Differences handled here, so the two versions cannot drift:
  * one flat folder, no \\input of section files (the journal asks for a single
    .tex file and no sub-folders): every section and table is inlined;
  * only the numeric macros actually used are written into the preamble;
  * author-year citations (natbib): \\cite -> \\citep, and 'Name et al.~\\cite'
    -> \\citet;
  * algorithmic (uppercase commands) -> algpseudocode;
  * figure captions lose their final period; figures are copied flat.
"""

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
SRC = ROOT / "manuscript" / "latex"
OUT = ROOT / "manuscript" / "ese"

ORDER = ["1_intro", "2_background", "3_method", "4a_setup", "4b_rq1",
         "4c_rq2", "4e_info", "4d_rq3", "4f_ablation", "4g_reference",
         "4h_summary", "5_discussion", "6_conclusion"]


def inline_inputs(text):
    def rep(m):
        name = m.group(1)
        p = SRC / (name if name.endswith(".tex") else name + ".tex")
        body = p.read_text()
        body = "\n".join(l for l in body.splitlines()
                         if not l.startswith("% Generated by")
                         and not l.startswith("% Every value is read"))
        return inline_inputs(body)
    return re.sub(r"\\input\{([^}]+)\}", rep, text)


def algorithmic(text):
    pairs = [(r"\\REQUIRE", r"\\Require"), (r"\\STATE", r"\\State"),
             (r"\\FOR\{", r"\\For{"), (r"\\ENDFOR", r"\\EndFor"),
             (r"\\IF\{", r"\\If{"), (r"\\ELSE", r"\\Else"),
             (r"\\ENDIF", r"\\EndIf"), (r"\\RETURN", r"\\State \\Return"),
             (r"\\COMMENT\{", r"\\Comment{")]
    for a, b in pairs:
        text = re.sub(a, b, text)
    text = text.replace("\\begin{algorithmic}[1]", "\\begin{algorithmic}[1]")
    return text


def citations(text):
    text = re.sub(r"[A-Z][\w\-']+\s+et\s+al\.~?\s*\\cite\{([^}]*)\}", r"\\citet{\1}", text)
    text = re.sub(r"\\cite\{", r"\\citep{", text)
    return text


def figure_captions(text):
    def fix(m):
        cap = m.group(0)
        return re.sub(r"\.\}(\s*\\label\{fig:)", r"}\1", cap)
    return re.sub(r"\\caption\{.*?\}\s*\\label\{fig:[^}]*\}", fix, text, flags=re.S)


def used_macros(body, numbers):
    defs = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{(.*)\}", numbers))
    used = set(re.findall(r"\\((?:num|m[BD]v|c[BD]v)\w*)", body + ABSTRACT))
    # a macro can also be used inside another macro's value (none are)
    lines = [f"\\newcommand{{\\{k}}}{{{defs[k]}}}" for k in sorted(used) if k in defs]
    missing = sorted(u for u in used if u not in defs)
    return "\n".join(lines), missing


def main():
    global ABSTRACT
    tmpl = (OUT / "main_template.tex").read_text()
    ABSTRACT = tmpl
    parts = []
    for name in ORDER:
        parts.append((SRC / f"{name}.tex").read_text())
    body = "\n\n".join(parts)
    body = inline_inputs(body)
    body = algorithmic(body)
    body = citations(body)
    body = figure_captions(body)
    body = body.replace("\\resizebox{\\linewidth}{!}{%", "\\adjustbox{max width=\\textwidth}{%")
    body = body.replace("\\begin{table*}[t]", "\\begin{tableorg}[t]").replace("\\end{table*}", "\\end{tableorg}")
    body = body.replace("\\begin{table}[t]", "\\begin{tableorg}[t]").replace("\\end{table}", "\\end{tableorg}")
    macros, missing = used_macros(body, (SRC / "numbers.tex").read_text())
    if missing:
        print("UNDEFINED macros:", missing)
    out = tmpl.replace("%%NUMBERS%%", macros).replace("%%BODY%%", body)
    (OUT / "main.tex").write_text(out)
    for f in ("fig_redundancy.pdf", "fig_representation_forest.pdf"):
        shutil.copy(ROOT / "manuscript" / "figures" / f, OUT / f)
    shutil.copy(SRC / "ref.bib", OUT / "ref.bib")
    out_text = (OUT / "main.tex").read_text()
    out_text = out_text.replace("figures/fig_", "fig_")
    (OUT / "main.tex").write_text(out_text)
    print(f"wrote {OUT/'main.tex'} ({len(out_text.splitlines())} lines, "
          f"{len(macros.splitlines())} macros)")


if __name__ == "__main__":
    sys.exit(main())
